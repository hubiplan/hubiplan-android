#!/usr/bin/env python3
"""Ergänzt in gradle/verification-metadata.xml die Prüfsummen plattformabhängiger Artefakte.

Gradle schreibt nur, was es auf dem eigenen Rechner lädt. aapt2 (Android-Gradle-Plugin) gibt es
je Betriebssystem als eigene Datei (…-linux.jar, …-windows.jar, …-osx.jar); ein Lauf unter Linux
trüge nur die Linux-Fassung ein, und unter Windows oder macOS bräche dann jeder Bau ab. Das
Skript sucht solche Artefakte und trägt die fehlenden Fassungen nach. Die Dateien lädt es aus
dem Google-Maven-Verzeichnis (dasselbe wie google() in settings.gradle.kts).

    scripts/pruefsummen_plattformen.py [Datei]
"""
import hashlib
import os
import re
import sys
import urllib.request

PLATTFORMEN = ("linux", "osx", "windows")
QUELLE = os.environ.get("PRUEFSUMMEN_QUELLE", "https://dl.google.com/dl/android/maven2")


def laden(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=120) as antwort:
        return antwort.read()


def ergaenzen(text: str) -> tuple[str, list[str]]:
    neu: list[str] = []

    def komponente(m: re.Match) -> str:
        kopf, gruppe, name, fassung, inhalt, ende = m.groups()
        vorhanden = set(re.findall(r'<artifact name="([^"]+)"', inhalt))
        stamm = f"{name}-{fassung}-"
        plattformen = {a[len(stamm):-4] for a in vorhanden
                       if a.startswith(stamm) and a.endswith(".jar") and a[len(stamm):-4] in PLATTFORMEN}
        if not plattformen:
            return m.group(0)
        bloecke = {n: b for b, n in re.findall(r'(?s)( *<artifact name="([^"]+)">.*?</artifact>\n)', inhalt)}
        for p in PLATTFORMEN:
            datei = f"{stamm}{p}.jar"
            if datei in bloecke:
                continue
            url = f"{QUELLE}/{gruppe.replace('.', '/')}/{name}/{fassung}/{datei}"
            summe = hashlib.sha256(laden(url)).hexdigest()
            bloecke[datei] = (
                f'         <artifact name="{datei}">\n'
                f'            <sha256 value="{summe}" origin="Generated by scripts/pruefsummen_plattformen.py"/>\n'
                f'         </artifact>\n'
            )
            neu.append(f"{gruppe}:{name}:{fassung} {datei}")
        rest = re.sub(r'(?s) *<artifact name="[^"]+">.*?</artifact>\n', "", inhalt)
        return kopf + "".join(bloecke[n] for n in sorted(bloecke)) + rest + ende

    muster = re.compile(
        r'(?s)(<component group="([^"]+)" name="([^"]+)" version="([^"]+)">\n)(.*?)(</component>)')
    return muster.sub(komponente, text), neu


def main() -> int:
    pfad = sys.argv[1] if len(sys.argv) > 1 else "gradle/verification-metadata.xml"
    with open(pfad, encoding="utf-8") as f:
        text = f.read()
    text, neu = ergaenzen(text)
    if neu:
        with open(pfad, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    for zeile in neu:
        print(f"Plattform ergänzt: {zeile}")
    if not neu:
        print("Plattformabhängige Artefakte: alle Fassungen vorhanden.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
